test('claim needs a booked counter and completion advances only the current claimant', async t => {
  signIn(t);
  t.mock.method(User, 'findOne', () => chain({ role: 'Faculty', _id: userid }));
  const nextId = '333333333333333333333333';
  const lookup = t.mock.method(Level, 'findOne', query => chain(query.level ? { _id: nextId, level: 3, title: 'Final' } : { _id: id, level: 1 }));
  t.mock.method(Token, 'findOne', () => chain({ levelid: id, level: 1, programcode: '001', day: '2026-11-11' }));
  let booked = false;
  t.mock.method(Booking, 'findOne', () => chain(booked ? { counterid: nextId } : null));
  t.mock.method(Counter, 'findOne', () => chain({ number: 'A1' }));
  const update = t.mock.method(Token, 'updateOne', async () => ({ matchedCount: 1 }));
  assert.equal((await post('/tokens/:id/:action', {}, { id, action: 'claim' })).status, 400);
  booked = true;
  assert.equal((await post('/tokens/:id/:action', {}, { id, action: 'claim' })).status, 200);
  assert.equal(update.mock.calls[0].arguments[0].status, 'Waiting');
  assert.equal(update.mock.calls[0].arguments[1].$set.counter, 'A1');
  assert.equal((await post('/tokens/:id/:action', {}, { id, action: 'complete' })).data.message, 'Token sent to Level 3');
  assert.equal(lookup.mock.calls.at(-1).arguments[0].active, 'Yes');
  assert.equal(update.mock.calls[1].arguments[0].claimedby, userid);
  assert.equal(update.mock.calls[1].arguments[1].$set.levelid, nextId);
});
test('public display validates the exact institution and program and projects no lead details', async t => {
  const old = process.env.JWT_SECRET; process.env.JWT_SECRET = 'unit-test-secret';
  t.after(() => { if (old === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = old; });
  const verify = jwt.verify;
  const login = t.mock.method(jwt, 'verify', () => ({ colid: 42, user: 'admin@example.com' }));
  t.mock.method(User, 'findOne', () => chain({ role: 'All' }));
  t.mock.method(Level, 'exists', async () => true);
  const { data } = await post('/display-link', { programcode: '001' });
  login.mock.restore();
  assert.throws(() => verify(data.permission, process.env.JWT_SECRET), /invalid signature/);
  t.mock.method(Level, 'findOne', () => chain({ program: 'Engineering' }));
  const query = chain([{ number: 1, level: 1, counter: 'A1' }]);
  const select = t.mock.method(query, 'select', () => query);
  const find = t.mock.method(Token, 'find', () => query);
  const handler = router.stack.find(layer => layer.route?.path === '/public-display').route.stack[0].handle;
  const read = async colid => {
    let code = 200;
    await handler({ get: () => `Bearer ${data.permission}`, query: { colid, programcode: '001' } }, { status(n) { code = n; return this; }, json() {}, set() { return this; } });
    return code;
  };
  assert.equal(await read('99'), 403);
  assert.equal(await read('42'), 200);
  assert.equal(find.mock.calls[0].arguments[0].colid, 42);
  assert.equal(select.mock.calls[0].arguments[0], 'number level title counter status -_id');
});
