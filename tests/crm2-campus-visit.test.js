const test=require('node:test'),assert=require('node:assert/strict'),mongoose=require('mongoose');
const router=require('../controllers/crm2PublicLeadForms');
const {Lead}=require('../Models/crm2ds');
const Program=require('../Models/mprograms'),Level=require('../Models/crm2campusqueuelevel');
const {Token,Sequence}=require('../Models/crm2campusqueue');
const chain=value=>({sort(){return this;},lean:async()=>value});
test('campus visit derives scoped program, uses lowest active level and never assigns a counsellor',async t=>{
 const id='111111111111111111111111';
 t.mock.method(mongoose.model('crm2publicleadform'),'findOne',()=>chain({_id:id,colid:42,campus:true,fields:['name','email','phone'],source:'Visit',utmsource:'Walk in'}));
 t.mock.method(mongoose.model('crm2leadformcaptcha'),'findOneAndDelete',async()=>({answer:'12'}));
 const program=t.mock.method(Program,'findOne',()=>chain({_id:id,program:'Science',programcode:'SCI',year:'2026-27'}));
 const level=t.mock.method(Level,'findOne',()=>chain({_id:id,level:2,title:'Reception'}));
 t.mock.method(Lead,'find',()=>chain([]));
 const create=t.mock.method(Lead,'create',async row=>({...row,_id:id}));
 const update=t.mock.method(Lead,'updateOne',async()=>({}));
 t.mock.method(Token,'findOne',async()=>null);
 t.mock.method(Sequence,'findOneAndUpdate',async()=>({value:9}));
 const issue=t.mock.method(Token,'create',async row=>row);
 let status=200,result;
 const handler=router.stack.find(layer=>layer.route?.path==='/public/:key'&&layer.route.methods.post).route.stack.at(-1).handle;
 await handler({params:{key:'public'},body:{programid:id,colid:99,captchaid:'captcha',captchaanswer:'12',data:{name:'Visitor',email:'visit@example.com',phone:'9000000000',counselloremail:'spoof@example.com'}}},{status(value){status=value;return this;},json(value){result=value;}});
 assert.equal(status,200);
 assert.deepEqual(program.mock.calls[0].arguments[0],{_id:id,colid:42});
 assert.deepEqual(level.mock.calls[0].arguments[0],{colid:42,programcode:'SCI',active:'Yes'});
 assert.equal(create.mock.calls[0].arguments[0].counselloremail,undefined);
 assert.equal(create.mock.calls[0].arguments[0].campuswalkin,true);
 assert.equal(update.mock.calls[1].arguments[1].$push.programsinterested.programcode,'SCI');
 assert.equal(issue.mock.calls[0].arguments[0].level,2);
 assert.equal(issue.mock.calls[0].arguments[0].status,'Waiting');
 assert.match(result.message,/token is 9/);
});
